/**
 * Подготовка сервера перед первым запросом.
 *
 * `register` вызывается один раз при запуске и обязан завершиться до того, как
 * сервер начнёт отвечать. Это единственное место, где посев демо-данных не
 * гонится с запросами: делать его внутри обработчика значило бы получать
 * несколько одновременных попыток создать одну и ту же запись.
 */
export async function register(): Promise<void> {
  // На пограничной среде выполнения нет ни файловой системы, ни SQLite —
  // серверный модуль туда даже импортировать нельзя.
  if (process.env.NEXT_RUNTIME !== "nodejs") return;

  const { seedIfEmpty } = await import("./server/seed");
  await seedIfEmpty();
}
