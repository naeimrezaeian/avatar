/**
 * Отмена транзакции без всплытия AbortError.
 *
 * idb создаёт промис `tx.done` в момент открытия транзакции, а не при первом
 * обращении к нему. Поэтому намеренный `abort()` отклоняет этот промис, и если
 * его никто не ждёт — а в ветке с ошибкой мы его и не ждём, — отклонение
 * остаётся необработанным. В браузере это шумит в консоли и поднимает оверлей
 * ошибок Next в разработке, маскируя настоящие сбои.
 */
export function abortQuietly(tx: { abort: () => void; done: Promise<unknown> }): void {
  tx.abort();
  tx.done.catch(() => {});
}
